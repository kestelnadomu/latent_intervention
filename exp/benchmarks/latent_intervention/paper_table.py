"""LaTeX tabular of the standard-DAG latent editors for the paper appendix.

Reads the consolidated ``comparison.json`` of an editor comparison run and its
``references.json`` (see ``references.py``), so the paper never carries hand-copied
numbers. Rows are editors x latent width: the methods reported in the paper (minimal
edits, then constant-noise edits), followed by the references below a rule. Columns
separate test units that need an edit from units already at the target (``do(X=3)``
is the identity there). Only the bare ``tabular`` is written; the float and caption
are maintained by hand in the paper.

    .venv/bin/python -m exp.benchmarks.latent_intervention.paper_table \
        --run-id editor-clean-v1 --output overleaf/tables/standard_dag.tex
"""

import argparse
from pathlib import Path

from exp.benchmarks.semantic_decoder.paper_table import bold, cell, read_json

ROOT = Path("reports/talent/editor_benchmarks")
DIMENSIONS = (256, 768)
# Minimal edits (semantic and OT editor), then constant-noise edits.
METHODS = ("semantic_editor", "ot_editor", "state_flow", "ot_flow", "ot_gaussian")
REFERENCES = ("no_edit", "oracle_regression")
NAMES = {
    "semantic_editor": "Semantic editor",
    "ot_editor": "OT editor",
    "state_flow": "State flow",
    "ot_flow": "OT flow",
    "ot_gaussian": "Gaussian OT",
    "no_edit": "No edit",
    "oracle_regression": "Oracle regression",
}
# (subset, metric, label, better, digits, scale)
COLUMNS = (
    ("nonidentity", "energy_score", "Energy $\\downarrow$", min, 3, 1),
    ("nonidentity", "semantic_kl", "Sem.\\ KL $\\downarrow$", min, 3, 1),
    ("nonidentity", "realized_joint_accuracy", "Joint acc.\\ (\\%) $\\uparrow$", max, 1, 100),
    ("identity", "mean_shift_l2", "Shift $\\downarrow$", min, 4, 1),
    ("identity", "realized_joint_accuracy", "Joint acc.\\ (\\%) $\\uparrow$", max, 1, 100),
)


def _load(run):
    comparison = read_json(run / "comparison.json")
    groups = {(g["variant"], g["dimension"]): g for g in comparison["groups"]}
    missing = {(v, d) for v in METHODS + REFERENCES for d in DIMENSIONS} - set(groups)
    if missing:
        raise ValueError(f"comparison has no results for {sorted(missing)}")
    return groups, read_json(run / "references.json")


def _moment(group, subset, metric):
    value = group["results"][subset]["metrics"][metric]
    return value["mean"], value["seed_sd"]


def _rows(groups, variants, best=None):
    rows = []
    for variant in variants:
        for d in DIMENSIONS:
            cells = [NAMES[variant] if d == DIMENSIONS[0] else "", str(d)]
            for subset, metric, _, _, digits, scale in COLUMNS:
                mean, sd = _moment(groups[(variant, d)], subset, metric)
                # Ties at the displayed precision are all bold.
                top = best[(d, subset, metric)] if best else None
                is_best = top is not None and f"{scale * mean:.{digits}f}" == f"{scale * top:.{digits}f}"
                cells.append(cell(mean, sd, digits, scale, is_best))
            rows.append(" & ".join(cells) + " \\\\")
    return rows


def render(run_id):
    run = ROOT / run_id
    groups, references = _load(run)
    best = {
        (d, subset, metric): better(_moment(groups[(v, d)], subset, metric)[0] for v in METHODS)
        for d in DIMENSIONS
        for subset, metric, _, better, _, _ in COLUMNS
    }
    body = [*_rows(groups, METHODS, best), "\\midrule", *_rows(groups, REFERENCES)]

    bayes = references["bayes_optimal"]["metrics"]
    cells = ["Bayes-optimal", "--"]
    for subset, metric, _, _, digits, scale in COLUMNS:
        value = bayes[subset].get(metric)
        cells.append("--" if value is None else cell(value, None, digits, scale))
    body.append(" & ".join(cells) + " \\\\")

    edit, keep = bayes["nonidentity"]["units"], bayes["identity"]["units"]
    header = (
        f"\\multicolumn{{3}}{{c}}{{{bold(f'Edit required ($n={edit}$)')}}} & "
        f"\\multicolumn{{2}}{{c}}{{{bold(f'No edit required ($n={keep}$)')}}}"
    )
    labels = " & ".join(bold(label) for _, _, label, *_ in COLUMNS)
    lines = [
        f"% Generated by exp/benchmarks/latent_intervention/paper_table.py from run {run_id}.",
        "% Do not edit by hand; regenerate instead. The table float and caption live in",
        "% appendix/results_standard_dag.tex.",
        "\\begin{tabular}{@{}lr" + "r" * len(COLUMNS) + "@{}}",
        "  \\toprule",
        f"  & & {header} \\\\",
        "  \\cmidrule(lr){3-5} \\cmidrule(lr){6-7}",
        f"  {bold('Method')} & {bold('$d$')} & {labels} \\\\",
        "  \\midrule",
        *[f"  {line}" for line in body],
        "  \\bottomrule",
        "\\end{tabular}",
    ]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--run-id", required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(render(args.run_id), encoding="utf-8")
    print(f"wrote {args.output}")


if __name__ == "__main__":
    main()
