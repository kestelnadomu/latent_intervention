"""LaTeX tabular of every encoder x semantic-decoder case for the paper appendix.

Reads a completed run's frozen JSON (results, evaluation) and its
``references.json`` (see ``references.py``), so the paper never carries hand-copied
numbers. Rows are latent spaces grouped by encoder family; each metric shows the
independent and autoregressive decoder side by side. Only the bare ``tabular`` is
written; the float, formatting and caption are maintained by hand in the paper.

    .venv/bin/python -m exp.benchmarks.semantic_decoder.paper_table \
        --run-id g-all-encoders-v1 --output overleaf/tables/encoder_decoder.tex
"""

import argparse
import json
import re
from pathlib import Path

ROOT = Path("reports/talent/decoder_benchmarks")
VARIANTS = ("independent", "autoregressive")
FAMILIES = {
    "langvae": "LangVAE",
    "langvae_ft": "LangVAE-FT",
    "nomic": "Nomic Embed v1.5",
    "qwen3": "Qwen3-Embedding-0.6B",
    "embeddinggemma": "EmbeddingGemma-300m",
}
# (label, results/evaluation accessor, better, digits, scale)
METRICS = (
    ("Val.\\ NLL $\\downarrow$", "validation_nll", min, 3, 1),
    ("Test NLL $\\downarrow$", "test_nll", min, 3, 1),
    ("Test joint acc.\\ (\\%) $\\uparrow$", "test_accuracy", max, 1, 100),
)


def _family(tag):
    return tag if tag in FAMILIES else re.sub(r"_\d+$", "", tag)


def _group(family):
    """Stock and fine-tuned LangVAE share one block of the table."""
    return "langvae" if family == "langvae_ft" else family


def bold(text):
    """Bold header text, including its math (plain \\textbf leaves math upright)."""
    return f"{{\\bfseries\\boldmath {text}}}"


def cell(mean, sd, digits, scale=1, best=False):
    """Mean with a tiny seed SD; ``sd=None`` marks a single run and prints no SD."""
    text = f"{scale * mean:.{digits}f}"
    if best:
        text = f"\\textbf{{{text}}}"
    if sd is None:
        return text
    return f"{text}{{\\tiny$\\pm${f'{scale * sd:.{digits}f}'.removeprefix('0')}}}"


def read_json(path):
    return json.loads(Path(path).read_text(encoding="utf-8"))


def _load(run):
    evaluation = {e["case"]: e for e in read_json(run / "evaluation.json")}
    cases = {}
    for r in read_json(run / "results.json"):
        test = evaluation[r["case"]]["factual_test"]
        cases[r["case"]] = {
            "tag": r["encoder_tag"],
            "dim": r["latent_dimension"],
            "decoder": r["decoder"],
            "validation_nll": r["summary"]["validation_joint_nll"],
            "test_nll": test["joint_nll"],
            "test_accuracy": test["joint_map_accuracy"],
        }
    return cases, read_json(run / "references.json")


def render(run_id):
    run = ROOT / run_id
    cases, references = _load(run)
    if len(cases) != 2 * len({c["tag"] for c in cases.values()}):
        raise ValueError("every latent space needs both decoder variants")
    best = {
        key: better(c[key]["mean"] for c in cases.values())
        for _, key, better, _, _ in METRICS
    }

    tags = sorted(
        {c["tag"] for c in cases.values()},
        key=lambda t: (list(FAMILIES).index(_family(t)), cases[f"{t}/g-independent"]["dim"]),
    )
    body, previous = [], None
    for tag in tags:
        family = _family(tag)
        if previous is not None and _group(family) != _group(previous):
            body.append("\\midrule")
        label = FAMILIES[family] if family != previous else ""
        cells = [label, str(cases[f"{tag}/g-independent"]["dim"])]
        for _, key, _, digits, scale in METRICS:
            for variant in VARIANTS:
                moment = cases[f"{tag}/g-{variant}"][key]
                cells.append(
                    cell(moment["mean"], moment["std"], digits, scale, moment["mean"] == best[key])
                )
        body.append(" & ".join(cells) + " \\\\")
        previous = family

    body.append("\\midrule")
    for key, label in (("prior", "Null model"), ("bayes_optimal", "Bayes-optimal")):
        metrics = references[key]["metrics"]
        cells = [label, "--"]
        for split_name, metric, digits, scale in (
            ("validation", "joint_nll", 3, 1),
            ("test", "joint_nll", 3, 1),
            ("test", "joint_map_accuracy", 1, 100),
        ):
            value = f"{scale * metrics[split_name][metric]:.{digits}f}"
            cells.append(f"\\multicolumn{{2}}{{c}}{{{value}}}")
        body.append(" & ".join(cells) + " \\\\")

    header = " & ".join(
        f"\\multicolumn{{2}}{{c}}{{{bold(label)}}}" for label, *_ in METRICS
    )
    rules = " ".join(f"\\cmidrule(lr){{{3 + 2 * i}-{4 + 2 * i}}}" for i in range(len(METRICS)))
    variants = " & ".join(bold(f"{v} $\\psi$") for v in VARIANTS * len(METRICS))
    lines = [
        f"% Generated by exp/benchmarks/semantic_decoder/paper_table.py from run {run_id}.",
        "% Do not edit by hand; regenerate instead. The table float and caption live in",
        "% appendix/encoder.tex.",
        "\\begin{tabular}{@{}lr" + "rr" * len(METRICS) + "@{}}",
        "  \\toprule",
        f"  & & {header} \\\\",
        f"  {rules}",
        f"  {bold('Encoder $\\varphi$')} & {bold('$d$')} & {variants} \\\\",
        "  \\midrule",
        *[f"  {line}" for line in body],
        "  \\bottomrule",
        "\\end{tabular}",
    ]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--run-id", required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(render(args.run_id), encoding="utf-8")
    print(f"wrote {args.output}")


if __name__ == "__main__":
    main()
