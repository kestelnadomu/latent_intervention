"""LaTeX content of the simulation appendix: text pools, prompts and a worked example.

Writes only content (escaped texts, two tabulars and a few macros) into one directory;
boxes, captions and prose are maintained by hand in ``overleaf/appendix/simulation.tex``.

- ``pool_overview.tex``: tabular summarizing every text pool and the CVs.
- ``job_titles.tex``: the job titles as one list; titles no persona uses get ``$^\\ast$``.
- ``seeds.tex``, ``templates.tex``, ``personas.tex``: the full pools.
- ``prompt_{template,persona,cv}.tex``: the generation prompts, placeholders marked.
- ``example_*.tex``: one unit traced from its seed statement to its CVs x and x'.

The worked example is the evaluation unit whose counterfactual changes region, degree
and university at once and whose CV pair is shortest (``--unit`` overrides). Its prompt
inputs are rebuilt with the simulator's own ``RenderContext.render_inputs``. Phrases the
intervention changes are wrapped in ``\\changed``, template slots in ``\\slot`` and prompt
placeholders in ``\\promptvar``; the appendix defines these macros.

Run from a checkout that contains the talent-motivation simulation (e.g. ``main``):

    .venv/bin/python -m exp.sim.paper_appendix \\
        --config exp/sim_talent_motivation/config.yaml --output overleaf/generated/simulation
"""

import argparse
import re
from pathlib import Path

import pandas as pd
import yaml

from exp.sim.helpers import load_sim_config
from exp.sim.render import render_context

SEEDS = Path("exp/sim/seed_statements.yaml")
JOB_TITLES = Path("exp/sim/job_titles.yaml")
PROMPTS = {
    "template": Path("exp/sim/prompts/template_generation.yaml"),
    "persona": Path("exp/sim/prompts/persona_generation.yaml"),
}
# Paper notation (O for the code's X) and the names used in Section 4.
VARIABLES = {
    "X": ("O", "region of origin"),
    "T": ("T", "talent"),
    "D": ("D", "degree"),
    "U": ("U", "university rank"),
    "P": ("P", "completed projects"),
    "L": ("L", "learning speed"),
    "H": ("H", "hard problems"),
    "A": ("A", "sought out for advice"),
    "M": ("M", "motivation"),
    "Y": ("Y", "qualification"),
}
STATED = ("X", "D", "U")  # stated facts the intervention can change
HEADER = "% Generated by exp/sim/paper_appendix.py. Do not edit by hand; regenerate instead.\n"
_SPECIAL = {
    "\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#",
    "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}",
}


def esc(text):
    return re.sub(r"[\\&%$#_{}~^]", lambda m: _SPECIAL[m[0]], str(text))


def words(text):
    return len(str(text).split())


def _marked(text, pattern, macro):
    """Escape ``text`` and wrap every ``pattern`` match (group 1 if present) in ``macro``."""
    out, last = [], 0
    for m in re.finditer(pattern, text):
        inner = m[1] if m.groups() else m[0]
        out += [esc(text[last:m.start()]), f"\\{macro}{{{esc(inner)}}}"]
        last = m.end()
    return "".join(out) + esc(text[last:])


def slots(text):
    return _marked(text, r"\[([^\[\]]+)\]", "slot")


def paragraphs(text, render=esc):
    return "\n\n".join(render(" ".join(p.split())) for p in re.split(r"\n\s*\n", text.strip()))


def template_tex(text):
    """Key points as a compact list, the narrative as paragraphs; markdown emphasis dropped."""
    text = re.sub(r"(?<!\*)\*([^*\n]+)\*(?!\*)", r"\1", text.replace("**", ""))
    out, items = [], []

    def flush():
        if items:
            out.append("\\begin{enumerate}\\setlength{\\itemsep}{0pt}\n" + "\n".join(items) + "\n\\end{enumerate}")
            items.clear()

    for line in (line.strip() for line in text.splitlines()):
        if not line:
            continue
        if m := re.fullmatch(r"(Key Points|Narrative Template)\s*:?\s*(.*)", line):
            flush()
            out.append(f"\\textbf{{{m[1]}.}}" + (f" {slots(m[2])}" if m[2] else ""))
        elif m := re.fullmatch(r"\d+\.\s*(.*)", line):
            label = re.match(r"([^:]{1,60}):\s*(.*)", m[1])
            items.append(f"\\item \\textbf{{{esc(label[1])}:}} {slots(label[2])}" if label else f"\\item {slots(m[1])}")
        else:
            flush()
            out.append(slots(line))
    flush()
    return "\n\n".join(out)


def persona_tex(text):
    return "\n\n".join(
        f"\\textbf{{{esc(m[1])}:}} {esc(m[2])}" if (m := re.fullmatch(r"([A-Z][A-Za-z ]+):\s*(.*)", line.strip())) else esc(line)
        for line in text.strip().splitlines() if line.strip()
    )


def prompt_tex(prompt):
    """System and user message, line breaks kept, ``{placeholders}`` marked."""

    def body(text):
        blocks = []
        for block in re.split(r"\n\s*\n", text.strip()):
            lines = [
                ("\\hspace*{1.5em}" if line[:1].isspace() else "") + _marked(line.strip(), r"\{([a-z_]+)\}", "promptvar")
                for line in block.splitlines()
            ]
            blocks.append(" \\newline\n".join(lines))
        return "\n\n".join(blocks)

    return f"\\textbf{{System.}} {body(prompt['system'])}\n\n\\textbf{{User.}} {body(prompt['user'])}\n"


def changed(text, phrases):
    """Escape a CV and mark the given phrases (apostrophe style and case ignored)."""
    if not phrases:
        return esc(text)
    alternatives = "|".join(re.sub("['’]", "['’]", re.escape(p)) for p in phrases)
    return _marked(text, f"(?i)({alternatives})", "changed")


def seed_list():
    raw = SEEDS.read_text(encoding="utf-8")
    sources = re.findall(r"# Source: (\S+)", raw)
    seeds = yaml.safe_load(raw)
    subjects = [re.search(r"examples/([^/]+)/", url)[1].replace("-", " ") for url in sources]
    if not len(seeds) == len(sources):
        raise ValueError("every seed statement needs one '# Source:' comment")
    return seeds, sources, subjects


def prompt_meta(prompt):
    model = prompt["metadata"]["model"].replace("gpt", "GPT")
    return f"{model}, temp.\\ {prompt['metadata']['temperature']:g}"


def span(values):
    lo, hi = min(values), max(values)
    return f"{lo}" if lo == hi else f"{lo}--{hi}"


def length(series):
    counts = series.map(words)
    return f"{int(counts.median())} [{counts.min()}, {counts.max()}]"


def select_unit(ctx, factual_cv, counterfactual_cv):
    s, s_cf = ctx.factual_by_id, ctx.counterfactual_by_id
    candidates = [
        i for i in counterfactual_cv.index if all(s.at[i, c] != s_cf.at[i, c] for c in STATED)
    ]
    size = {i: words(factual_cv.at[i, "text"]) + words(counterfactual_cv.at[i, "text"]) for i in candidates}
    return min(candidates, key=lambda i: (size[i], i))


def info_pairs(info):
    return dict(part.split(": ", 1) for part in info.strip("[]").split(", ") if ": " in part)


def render(config_path, unit=None):
    config = load_sim_config(config_path)
    ctx = render_context(config)
    spec = ctx.spec
    files = {}

    seeds, sources, subjects = seed_list()
    titles = yaml.safe_load(JOB_TITLES.read_text(encoding="utf-8"))
    templates, personas = ctx.templates, ctx.personas
    prompts = {k: yaml.safe_load(p.read_text(encoding="utf-8"))["prompt"] for k, p in PROMPTS.items()}
    prompts["cv"] = yaml.safe_load(Path(config["prompts"]["cv"]).read_text(encoding="utf-8"))["prompt"]
    factual_cv = pd.read_csv(config["paths"]["texts"]).set_index("id")
    counterfactual_cv = pd.read_csv(config["paths"]["texts_counterfactual"]).set_index("id")

    # Full pools.
    files["seeds"] = "\n\n".join(
        f"\\poolitem{{Seed statement {k}}}{{{esc(subject)}; \\url{{{url}}}}}\n{paragraphs(seed)}"
        for k, (seed, url, subject) in enumerate(zip(seeds, sources, subjects), start=1)
    )
    files["templates"] = "\n\n".join(
        f"\\poolitem{{Template {t}}}{{from seed statement {int(row.seed_id)}, {esc(subjects[int(row.seed_id) - 1])}}}\n{template_tex(row.text)}"
        for t, row in templates.iterrows()
    )
    files["personas"] = "\n\n".join(
        f"\\poolitem{{Persona {p}}}{{{esc(row.job_title)}}}\n{persona_tex(row.text)}"
        for p, row in personas.iterrows()
    )
    used = set(personas["job_title"])
    files["job_titles"] = ", ".join(esc(t) + ("" if t in used else "$^\\ast$") for t in titles) + "."
    for key, prompt in prompts.items():
        files[f"prompt_{key}"] = prompt_tex(prompt)

    # Pool overview.
    key_points = templates["text"].str.count(r"(?m)^\s*\d+\.")
    slot_counts = templates["text"].str.count(r"\[[^\[\]]+\]")
    seed_paragraphs = [len(re.split(r"\n\s*\n", s.strip())) for s in seeds]
    cv_paragraphs = factual_cv["text"].map(lambda t: len(re.split(r"\n\s*\n", t.strip())))
    labels = sorted(set(re.findall(r"(?m)^([A-Z][A-Za-z ]+):", "\n".join(personas["text"]))), key=lambda x: personas["text"].iloc[0].find(x))
    rows = [
        ("Seed statements", len(seeds), "curated",
         length(pd.Series(seeds)), f"Free text, {span(seed_paragraphs)} paragraphs"),
        ("Narrative templates", len(templates), prompt_meta(prompts["template"]), length(templates["text"]),
         f"{span(key_points)} key points and a narrative with {span(slot_counts)} slots"),
        ("Job titles", len(titles), "curated",
         f"{span([words(t) for t in titles])}", f"{len(used)} titles are sampled for personas"),
        ("Personas", len(personas), prompt_meta(prompts["persona"]), length(personas["text"]),
         f"{len(labels)} sections: " + ", ".join(label.lower() for label in labels)),
        ("Factual CVs $x$", len(factual_cv),
         prompt_meta(prompts["cv"]), length(factual_cv["text"]), f"{span(cv_paragraphs)} paragraphs"),
        ("Counterfactual CVs $x'$", len(counterfactual_cv),
         prompt_meta(prompts["cv"]), length(counterfactual_cv["text"]), "As $x$"),
    ]
    rows = [(name, f"{n:,}".replace(",", "{,}"), *rest) for name, n, *rest in rows]
    body = " \\\\\n".join("  " + " & ".join(str(c) for c in r) for r in rows)
    files["pool_overview"] = (
        "\\begin{tabular}{@{}p{3.0cm}r p{2.3cm} l p{5.4cm}@{}}\n  \\toprule\n"
        "  \\textbf{Pool} & \\textbf{$n$} & \\textbf{Generated by} & "
        "\\textbf{Words} & \\textbf{Structure} \\\\\n  \\midrule\n" + body + " \\\\\n  \\bottomrule\n\\end{tabular}"
    )

    # Worked example.
    unit = unit or select_unit(ctx, factual_cv, counterfactual_cv)
    plan = ctx.plan_by_id.loc[unit]
    template_id, persona_id = int(plan["template_id"]), int(plan["persona_id"])
    seed_id = int(templates.at[template_id, "seed_id"])
    inputs = {cf: ctx.render_inputs(unit, cf) for cf in (False, True)}
    for cf, (_, concrete) in inputs.items():
        stored = (counterfactual_cv if cf else factual_cv).loc[unit]
        for column, header in ctx.headers.items():
            if column in concrete and int(stored[header]) != int(concrete[column]):
                raise ValueError(f"rebuilt prompt input {column} differs from the stored CV of unit {unit}")
    info = {cf: info_pairs(sample["candidate_info"]) for cf, (sample, _) in inputs.items()}
    differing = [k for k in info[False] if info[False][k] != info[True][k]]
    phrases = {cf: [info[cf][k] for k in differing] for cf in info}

    def info_line(cf):
        return ", ".join(f"{esc(k)}: " + (f"\\changed{{{esc(v)}}}" if k in differing else esc(v)) for k, v in info[cf].items())

    evidence = inputs[False][0]["evidence_guidance"]
    if evidence != inputs[True][0]["evidence_guidance"]:
        raise ValueError("evidence guidance must be identical for x and x'")
    files["example_inputs"] = (
        f"\\textbf{{Candidate's personal information.}} $x$: [{info_line(False)}] \\newline\n"
        f"$x'$: [{info_line(True)}]\n\n"
        "\\textbf{Evidence of how the candidate works} (identical for $x$ and $x'$):\n"
        "\\begin{itemize}\\setlength{\\itemsep}{0pt}\n"
        + "\n".join(f"\\item {esc(line.lstrip('- '))}" for line in evidence.splitlines())
        + "\n\\end{itemize}\n\n"
        f"\\textbf{{Forbidden terms.}} {esc(inputs[False][0]['forbidden_terms'])}."
    )
    first, *rest = re.split(r"\n\s*\n", seeds[seed_id - 1].strip())
    files["example_seed"] = esc(" ".join(first.split())) + (" [\\ldots]" if rest else "")
    files["example_template"] = template_tex(templates.at[template_id, "text"])
    files["example_persona"] = persona_tex(personas.at[persona_id, "text"])
    files["example_cv"] = paragraphs(factual_cv.at[unit, "text"], lambda p: changed(p, phrases[False]))
    files["example_cv_counterfactual"] = paragraphs(counterfactual_cv.at[unit, "text"], lambda p: changed(p, phrases[True]))

    s, s_cf = ctx.factual_by_id.loc[unit], ctx.counterfactual_by_id.loc[unit]
    concrete = {cf: inputs[cf][1] for cf in inputs}

    def value(column, cf):
        state = s_cf if cf else s
        level = int(state[column])
        if column in spec["choices"]:
            text = f"{spec['columns'][column][level]} ({spec['choices'][column][level][concrete[cf][column]]})"
        elif column in spec["bins"]:
            text = f"{concrete[cf][column]} ({spec['columns'][column][level]})"
        elif column in spec["columns"]:
            text = spec["columns"][column][level]
        else:
            text = f"level {level}"
        return re.sub(r"(\d)-(\d)", r"\1--\2", esc(text))

    table_rows = []
    for column, (name, meaning) in VARIABLES.items():
        role = "stated" if column in STATED + ("P",) else "shown" if column in spec["evidence"] else "--"
        cells = [value(column, False), value(column, True)]
        if s[column] != s_cf[column]:
            cells = [f"\\changed{{{c}}}" for c in cells]
        table_rows.append(f"  $\\texttt {name}$ & {esc(meaning)} & {role} & {cells[0]} & {cells[1]}")
    files["example_variables"] = (
        "\\begin{tabular}{@{}lll ll@{}}\n  \\toprule\n"
        "  \\multicolumn{2}{@{}l}{\\textbf{Variable}} & \\textbf{In CV} & \\textbf{Factual} & \\textbf{Counterfactual} \\\\\n"
        "  \\midrule\n" + " \\\\\n".join(table_rows) + " \\\\\n  \\bottomrule\n\\end{tabular}"
    )
    region = int(ctx.counterfactual_by_id.at[unit, "X"])
    files["example_meta"] = "\n".join(
        f"\\newcommand{{\\{name}}}{{{esc(v)}}}"
        for name, v in {
            "exUnit": unit, "exSeed": seed_id, "exSeedSubject": subjects[seed_id - 1],
            "exTemplate": template_id, "exPersona": persona_id,
            "exJobTitle": personas.at[persona_id, "job_title"],
            "exTarget": spec["columns"]["X"][region],
        }.items()
    )
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--config", required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--unit", type=int, help="worked-example unit (default: selection rule)")
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    for name, content in render(args.config, args.unit).items():
        (args.output / f"{name}.tex").write_text(HEADER + content.rstrip() + "\n", encoding="utf-8")
    print(f"wrote {len(list(args.output.glob('*.tex')))} files to {args.output}")


if __name__ == "__main__":
    main()
