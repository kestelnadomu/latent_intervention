"""LaTeX tabular of the text-decoder results for the paper appendix.

Renders only from ``paper_summary.json`` (see ``decoder_summary.py``), so the paper
never carries hand-copied numbers. The table reports counterfactual generation
(phi(x') -> x'): the two retained decoders, then their references below a rule;
columns are text similarity and rule-based fact accuracy for the SCM variables O, D,
U and the talent proxy P. The summary's reconstruction rows (z -> x) are not shown.
Only the bare ``tabular`` is written; the float and caption are maintained by hand
in the paper.

    .venv/bin/python -m exp.paper_tables.decoder_table --output overleaf/tables/decoder.tex
"""

import argparse
import json
from pathlib import Path

PILOT = Path("reports/talent/embeddinggemma_768/text-realizer-cf/cv-cf-pilot-v1")
DECODERS = {"original": "Factual-only decoder", "oracle": "Oracle-exposed decoder"}
TASK = "counterfactual"
REFERENCES = {"retrieval": "Retrieval", "unedited": "Unedited $x$"}
# (key, label, digits, scale); facts are accuracies in percent, all metrics higher-is-better.
COLUMNS = (
    ("character_similarity", "Char.\\ sim.", 3, 1),
    ("chrf", "chrF", 3, 1),
    ("region", "$\\texttt O$", 1, 100),
    ("degree", "$\\texttt D$", 1, 100),
    ("university_tier", "$\\texttt U$", 1, 100),
    ("project_count", "$\\texttt P$", 1, 100),
)


def bold(text):
    """Bold header text, including its math (plain \\textbf leaves math upright)."""
    return f"{{\\bfseries\\boldmath {text}}}"


def cell(value, digits, scale, best=False):
    text = f"{scale * value:.{digits}f}"
    return f"\\textbf{{{text}}}" if best else text


def _value(entry, key):
    return entry["facts"][key]["accuracy"] if key in entry["facts"] else entry[key]


def render(summary_path):
    summary = json.loads(Path(summary_path).read_text(encoding="utf-8"))
    rows = summary["rows"][TASK]
    best = {key: max(_value(rows[d], key) for d in DECODERS) for key, *_ in COLUMNS}
    body = []
    for name, label in (*DECODERS.items(), *REFERENCES.items()):
        if name == next(iter(REFERENCES)):
            body.append("\\midrule")
        cells = [label]
        for key, _, digits, scale in COLUMNS:
            value = _value(rows[name], key)
            top = name in DECODERS and f"{scale * value:.{digits}f}" == f"{scale * best[key]:.{digits}f}"
            cells.append(cell(value, digits, scale, top))
        body.append(" & ".join(cells) + " \\\\")

    header = (
        f"& \\multicolumn{{2}}{{c}}{{{bold('Text similarity $\\uparrow$')}}} & "
        f"\\multicolumn{{4}}{{c}}{{{bold('Fact accuracy (\\%) $\\uparrow$')}}}"
    )
    labels = " & ".join(bold(label) for _, label, *_ in COLUMNS)
    lines = [
        f"% Generated by exp/paper_tables/decoder_table.py from {Path(summary_path).as_posix()}.",
        "% Do not edit by hand; regenerate instead. The table float and caption live in",
        "% appendix/decoder.tex.",
        "\\begin{tabular}{@{}l" + "r" * len(COLUMNS) + "@{}}",
        "  \\toprule",
        f"  {header} \\\\",
        "  \\cmidrule(lr){2-3} \\cmidrule(lr){4-7}",
        f"  {bold('Method')} & {labels} \\\\",
        "  \\midrule",
        *[f"  {line}" for line in body],
        "  \\bottomrule",
        "\\end{tabular}",
    ]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--summary", type=Path, default=PILOT / "paper_summary.json")
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(render(args.summary), encoding="utf-8")
    print(f"wrote {args.output}")


if __name__ == "__main__":
    main()
