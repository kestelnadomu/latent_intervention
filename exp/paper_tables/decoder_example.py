"""The decoded CVs of one evaluation unit for the decoder appendix, facts marked.

Reads the evaluation's per-unit texts (``scores/comparisons.jsonl``, checked against the
input hash in ``decoder_package_v1.json``) and writes the decoder's text from the predicted
vector z' and from the oracle vector phi(x') to ``overleaf/generated/decoder/``. Every fact
the evaluation scores is marked ``\\factright`` or ``\\factwrong`` against the true
counterfactual CV x', by the evaluation's own extractor. The country is judged by its
region, the variable the intervention sets; which country of the region a text names is
free. x' itself is ``generated/simulation/example_cv_counterfactual.tex``.

    python -m exp.paper_tables.decoder_example
"""

from __future__ import annotations

import hashlib
import json
import re
from pathlib import Path

import yaml

from exp.text_realizer.facts import extract

ROOT = Path(__file__).resolve().parents[2]
COMPARISONS = (
    ROOT
    / "reports/talent_motivation/text-realizer-evaluation/package-v1/scores/comparisons.jsonl"
)
SUMMARY = ROOT / "docs/experiments/results/decoder_package_v1.json"
CODEBOOK = ROOT / "exp/sim/codebook.yaml"
OUTPUT = ROOT / "overleaf/generated/decoder"
UNIT = 1898  # the worked example of the simulation appendix
DECODER = "768-270m"  # its z' is the paper's main pipeline (768-D state flow, seed 0)
NUMBER = r"(?:\d+|one|two|three|four|five|six|seven|eight|nine)"
# The spans behind exp.text_realizer.facts.extract, per field it scores.
PATTERNS = {
    "degree": r"\bbachelor(?:['’]s|s)?\b|\bmaster(?:['’]s|s)?\b|\b(?:doctorate|doctoral|ph\.?d\.?)\b",
    "university_tier": r"\b(?:unranked|not listed in (?:the )?(?:major )?global rankings)\b"
    r"|\b(?:global\s+)?top\s*(?:500|100)\b",
    "project_count": rf"\b{NUMBER}\s+(?:completed\s+)?projects?\b",
}
LATEX = {
    "\\": r"\textbackslash{}",
    "&": r"\&",
    "%": r"\%",
    "$": r"\$",
    "#": r"\#",
    "_": r"\_",
    "{": r"\{",
    "}": r"\}",
    "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
}


def escape(text: str) -> str:
    return "".join(LATEX.get(char, char) for char in text)


def marked(text: str, reference: str, codebook: dict) -> str:
    """``text`` as LaTeX, every scored fact marked right or wrong against ``reference``."""
    truth, found = extract(reference, codebook), extract(text, codebook)
    names = [
        n.removeprefix("the ") for ns in codebook["choices"]["X"].values() for n in ns
    ]
    patterns = {
        "region": r"\b(?:" + "|".join(map(re.escape, names)) + r")\b",
        **PATTERNS,
    }
    spans = sorted(
        (m.start(), m.end(), found[field] is not None and found[field] == truth[field])
        for field, pattern in patterns.items()
        for m in re.finditer(pattern, text, flags=re.IGNORECASE)
    )
    out, position = [], 0
    for start, end, right in spans:
        if start < position:
            continue  # overlapping matches: keep the first
        macro = r"\factright" if right else r"\factwrong"
        out += [escape(text[position:start]), f"{macro}{{{escape(text[start:end])}}}"]
        position = end
    return "".join(out + [escape(text[position:])])


def main() -> None:
    data = COMPARISONS.read_bytes()
    # line endings normalized: a CRLF checkout (core.autocrlf) is the same evaluated file
    if (
        hashlib.sha256(data.replace(b"\r\n", b"\n")).hexdigest()
        != json.loads(SUMMARY.read_text())["input_sha256"]
    ):
        raise ValueError("comparisons.jsonl is not the evaluated file")
    (row,) = [
        r for r in map(json.loads, data.decode("utf-8").splitlines()) if r["id"] == UNIT
    ]
    path = (
        CODEBOOK
        if len(text := CODEBOOK.read_text(encoding="utf-8")) > 260
        else CODEBOOK.parent / text.strip()
    )
    codebook = yaml.safe_load(
        path.read_text(encoding="utf-8")
    )  # (a symlink on Linux checkouts)
    OUTPUT.mkdir(parents=True, exist_ok=True)
    for condition in ("predicted", "oracle"):
        tex = marked(
            row["generated"][f"{DECODER}/{condition}"], row["reference"], codebook
        )
        path = OUTPUT / f"example_{condition}.tex"
        path.write_text(
            f"% Generated by exp/paper_tables/decoder_example.py (unit {UNIT}, decoder {DECODER}, "
            f"{condition} vector). Do not edit by hand; regenerate instead.\n{tex.strip()}\n",
            encoding="utf-8",
            newline="\n",
        )
        print(f"wrote {path}")


if __name__ == "__main__":
    main()
